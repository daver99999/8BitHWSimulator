#!/usr/bin/env python3
"""Test ROM for UD6: sums every 256 byte page of $B000-$E7FF and $F000-$FFFF as the CPU reads them through the
board, stores the sums at $8040.. (video RAM). usage: mksum.py out.bin ; then compare with sums.py"""
import sys
c = bytearray(); e = c.extend
e([0x78, 0xD8, 0xA2, 0xFF, 0x9A])                 # SEI CLD LDX #$FF TXS
e([0xA9, 0x00, 0x85, 0xFB, 0xA9, 0xB0, 0x85, 0xFC, 0xA2, 0x00])   # ptr=$B000, X=0
page = len(c) + 0xF000
e([0xA0, 0x00, 0xA9, 0x00, 0x85, 0xFD])           # LDY #0 ; LDA #0 ; STA $FD
inner = len(c) + 0xF000
e([0xB1, 0xFB, 0x18, 0x65, 0xFD, 0x85, 0xFD, 0xC8, 0xD0, 0xF6])  # LDA (FB),Y CLC ADC FD STA FD INY BNE inner
e([0xA5, 0xFD, 0x9D, 0x40, 0x80, 0xE8, 0xE6, 0xFC])  # LDA FD ; STA $8040,X ; INX ; INC FC
e([0xA5, 0xFC, 0xC9, 0xE8, 0xD0, 0x04, 0xA9, 0xF0, 0x85, 0xFC])  # LDA FC ; CMP #$E8 ; BNE +4 ; LDA #$F0 ; STA FC
e([0xA5, 0xFC, 0xF0, 0x03, 0x4C, page & 255, page >> 8])          # LDA FC ; BEQ done ; JMP page
done = len(c) + 0xF000
e([0x4C, done & 255, done >> 8])
rom = bytearray([0xFF] * 4096); rom[:len(c)] = c
rom[0xFFC], rom[0xFFD] = 0, 0xF0; rom[0xFFA], rom[0xFFB] = 0, 0xF0; rom[0xFFE], rom[0xFFF] = 0, 0xF0
open(sys.argv[1], 'wb').write(rom)

#!/usr/bin/env python3
"""ts1000i1_netlist2c.py - the board table src/ts1000i1_board_data.c (bd_ts1000i1): the ZX81/TS1000 Issue 1 board.
The circuit is the Issue 3's (tools/ts1000-netlist-src/ts1000_netlist.json: both are the SRC 049 drawing) with the two
resistor packs the Issue 1 has instead of R35-R47: RP1 (SIP9, 10K x 8: pin 1 the +5V common, pins 2-9 the data lines D0-D7) and RP3
(SIP6, 10K x 5: pin 1 the +5V common, pins 2-6 the keyboard columns KBD0-KBD4). Parts are placed from "ZX81 Issue 1 Layout" by
Dave 'Steamy' Briggs (tools/ts1000-netlist-src/placement_i1.py), the edge connector at the top.
Which pack pin is on which line is INFERRED (the drawing shows the packs in line order only); the keyboard connector KB2's pins
are read off the layout drawing, where its eight pins run 8 to 1 under the diodes' address lines A11 A10 A12 A9 A13 A8 A14 A15.
Usage: tools/ts1000i1_netlist2c.py [outdir]  (default: src)"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import ts1000_netlist2c as t
sys.path.insert(0, os.path.join(here, 'ts1000-netlist-src'))
import placement_i1 as pl

t.placement = pl
_footprint = t.footprint
def footprint(ref, typ, n):
    return 'R_Array_SIP%d' % n if typ in ('SIP9', 'SIP6') else _footprint(ref, typ, n)
t.footprint = footprint

_pads_at = t.pads_at
def pads_at(ref, typ, n):
    if ref in pl.SIP:
        px, py, orient, end = pl.SIP[ref]
        cx, cy = t.mm(px, py)
        out = []
        for i in range(n):
            a = (i - (n - 1) / 2) * 2.54                    # pin 1 at the dot end
            if orient == 'v': x, y = cx, cy + (-a if end == 'b' else a)
            else:             x, y = cx + (-a if end == 'r' else a), cy
            out.append((str(i + 1), x, y, 1.6, 1.6))
        return out
    if ref == 'J1':          # 46 contacts, contact k at x increasing, the component side (pad 2k-1, A) the row nearer the board
        px, py, orient, rows = pl.CONN['J1']
        cx, cy = t.mm(px, py)
        return [(str(i), cx + ((i - 1) // 2 - 11) * 2.54, cy + (1.27 if i % 2 else -1.27), 1.6, 1.6)
                for i in range(1, n + 1)]
    if ref in ('KB1', 'KB2'):  # pin 1 at the right
        px, py, orient, rows = pl.CONN[ref]
        cx, cy = t.mm(px, py)
        return [(str(i), cx + ((n - 1) / 2 - (i - 1)) * 2.54, cy, 1.6, 1.6) for i in range(1, n + 1)]
    return _pads_at(ref, typ, n)
t.pads_at = pads_at

def transform(chips, nets):
    for r in list(chips):
        if re.fullmatch(r'R(3[5-9]|4[0-7])', r): del chips[r]
    chips['RP1'] = 'SIP9'; chips['RP3'] = 'SIP6'
    for name in list(nets):
        nets[name] = [m for m in nets[name] if m.split('.')[0] in chips]
    nets['+5V'] += ['RP1.1', 'RP3.1']
    for i in range(8): nets['D%d' % i].append('RP1.%d' % (2 + i))
    for i in range(5): nets['KBD%d' % i].append('RP3.%d' % (2 + i))
    # KB2: the layout drawing runs its pins 8..1 under A11 A10 A12 A9 A13 A8 A14 A15 (the pin 1 at the right is A15)
    order = ['A15', 'A14', 'A8', 'A13', 'A9', 'A12', 'A10', 'A11']        # pin 1..8
    rowof = {'A%d' % (8 + i): 'ROW%d' % i for i in range(8)}
    for name in list(nets):
        nets[name] = [m for m in nets[name] if not m.startswith('KB2.')]
    for pin, a in enumerate(order, 1):
        nets[rowof[a]].append('KB2.%d' % pin)
    return chips, nets

if __name__ == '__main__':
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'src')
    chips, nets = t.read(os.path.join(here, 'ts1000-netlist-src', 'ts1000_netlist.json'))
    chips, nets = transform(chips, nets)
    t.emit(os.path.join(outdir, 'ts1000i1_board_data.c'), chips, nets, 'ts1000i1',
           'ZX81/TS1000 Issue 1 (the SRC 049 circuit, parts placed from the Issue 1 layout drawing)')
    f = os.path.join(outdir, 'ts1000i1_board_data.c')       # the shared emitter's header is the Issue 3's: say what this one is
    txt = open(f).read().replace('GENERATED by tools/ts1000_netlist2c.py', 'GENERATED by tools/ts1000i1_netlist2c.py')
    txt = txt.replace('the parts are placed in a rough layout until a photo of the board is available.', 'the Issue 1 differs by RP1/RP3 (resistor packs) in place of R35-R47, and the parts are placed from the Issue 1 layout drawing.')
    open(f, 'w').write(txt)

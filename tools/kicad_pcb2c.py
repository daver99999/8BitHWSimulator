#!/usr/bin/env python3
"""kicad_pcb2c.py - turn a KiCad PCB file (the nets and pads of the real board, at their real positions) into the board table of
the simulator: src/<prefix>_board_data.c (const board_data_t bd_<prefix>) and the part table src/<prefix>_parts.inc.
The pads' nets come from the PCB itself, so a schematic with nested sheets (which tools/apple2_sch2net.py cannot trace) is not needed.
Usage: tools/kicad_pcb2c.py <board.kicad_pcb> <prefix> "<comment>" [outdir]   (outdir default: src)
The machines' part maps (which chip value is which model) are in tools/pcbparts.py.
"""
import math, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import pcbparts


def parse(text):
    """a tiny s-expression reader: lists, with strings as ('s', text)"""
    tok = re.compile(r'\(|\)|"(?:[^"\\]|\\.)*"|[^\s()"]+')
    stack = [[]]
    for m in tok.finditer(text):
        t = m.group(0)
        if t == '(':
            stack.append([])
        elif t == ')':
            l = stack.pop()
            stack[-1].append(l)
        elif t[0] == '"':
            stack[-1].append(('s', t[1:-1].replace('\\"', '"').replace('\\\\', '\\')))
        else:
            stack[-1].append(t)
    return stack[0][0]


def head(l): return l[0] if l and isinstance(l[0], str) else None
def find(l, name): return [x for x in l if isinstance(x, list) and head(x) == name]
def sval(x): return x[1] if isinstance(x, tuple) else x


def num(x, d=0.0):
    try:
        return float(x)
    except (TypeError, ValueError):
        return d


def at_of(item):
    a = find(item, 'at')
    if not a: return 0.0, 0.0, 0.0, False
    a = a[0]
    return num(a[1]), num(a[2]), (num(a[3]) if len(a) > 3 else 0.0), len(a) > 3


def read_pcb(path):
    t = parse(open(path).read())
    parts = []
    for f in find(t, 'footprint') + find(t, 'module'):
        ref = val = None
        for x in find(f, 'fp_text'):
            if x[1] == 'reference': ref = sval(x[2])
            if x[1] == 'value': val = sval(x[2])
        for x in find(f, 'property'):
            if sval(x[1]) == 'Reference': ref = sval(x[2])
            if sval(x[1]) == 'Value': val = sval(x[2])
        fx, fy, frot, _ = at_of(f)
        layer = sval(find(f, 'layer')[0][1]) if find(f, 'layer') else 'F.Cu'
        back = layer.startswith('B.')
        pads = []
        for p in find(f, 'pad'):
            name = sval(p[1])
            if not name or p[2] in ('np_thru_hole',): continue
            px, py, prot, has = at_of(p)
            if not has: prot = frot
            # position: rotate by the footprint's angle (KiCad: counter-clockwise on the screen, y down)
            if back: px = -px
            th = math.radians(frot)
            ax = fx + px * math.cos(th) + py * math.sin(th)
            ay = fy - px * math.sin(th) + py * math.cos(th)
            sz = find(p, 'size')[0] if find(p, 'size') else ['size', '1', '1']
            w, h = num(sz[1]), num(sz[2])
            if round(prot) % 180 == 90: w, h = h, w
            net = None
            nn = find(p, 'net')
            if nn and len(nn[0]) > 2: net = sval(nn[0][2]) or None
            pads.append((name, ax, ay, w, h, net))
        if ref is None: continue
        fpname = sval(f[1]).split(':')[-1] if len(f) > 1 else ''
        parts.append(dict(ref=ref, value=val or '', fp=fpname, pads=pads))
    edge = []
    for e in find(t, 'gr_line') + find(t, 'gr_rect') + find(t, 'gr_arc'):
        lay = find(e, 'layer')
        if lay and sval(lay[0][1]) == 'Edge.Cuts':
            for k in ('start', 'end', 'mid'):
                for q in find(e, k): edge.append((num(q[1]), num(q[2])))
    return parts, edge


def sortkey(ref):
    m = re.match(r'([A-Za-z\-]+?)(\d+)?(.*)$', ref)
    return (m.group(1), int(m.group(2) or 0), m.group(3)) if m else (ref, 0, '')


def cstr(s): return s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)
    path, prefix, comment = sys.argv[1:4]
    outdir = sys.argv[4] if len(sys.argv) > 4 else os.path.join(here, '..', 'src')
    parts, edge = read_pcb(path)
    allpads = [p for c in parts for p in c['pads']]
    xs = [q[0] for q in edge] or [p[1] for p in allpads]
    ys = [q[1] for q in edge] or [p[2] for p in allpads]
    x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)
    nets = sorted({p[5] for p in allpads if p[5]})
    idx = {n: i for i, n in enumerate(nets)}
    out = ['/* %s_board_data.c - GENERATED by tools/kicad_pcb2c.py, do not edit.\n * %s */\n' % (prefix, comment)]
    out.append('#include "board_data.h"\n\nstatic const char *const nets[] = {')
    for n in nets: out.append('    "%s",' % cstr(n))
    out.append('};\n\nstatic const bd_pad_t pads[] = {')
    first, comps, k = {}, [], 0
    parts.sort(key=lambda c: sortkey(c['ref']))
    for c in parts:
        first[c['ref']] = k
        for (nm, px, py, w, h, net) in c['pads']:
            out.append('    { "%s", %.2ff, %.2ff, %.2ff, %.2ff, %d },' % (cstr(nm), px - x0, py - y0, w, h, idx[net] if net else -1))
            k += 1
        comps.append(c)
    out.append('};\n\nstatic const bd_comp_t comps[] = {')
    for c in comps:
        out.append('    { "%s", "%s", "%s", %d, %d },' % (cstr(c['ref']), cstr(c['value']), cstr(c['fp']), first[c['ref']], len(c['pads'])))
    out.append('};\n')
    out.append('const board_data_t bd_%s = {\n    { 0, 0, %.1ff, %.1ff },\n    nets, %d, pads, %d, comps, %d };\n' % (
        prefix, x1 - x0, y1 - y0, len(nets), k, len(comps)))
    cpath = os.path.join(outdir, prefix + '_board_data.c')
    open(cpath, 'w').write('\n'.join(out))
    inc = pcbparts.partdefs(prefix, parts)
    open(os.path.join(outdir, prefix + '_parts.inc'), 'w').write(inc[0])
    print(cpath, len(comps), 'parts', len(nets), 'nets', k, 'pads;', 'board %.0f x %.0f mm' % (x1 - x0, y1 - y0))
    for line in inc[1]: print('  unmodelled IC:', line)


if __name__ == '__main__':
    main()

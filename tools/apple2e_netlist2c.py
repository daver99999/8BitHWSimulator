#!/usr/bin/env python3
"""apple2e_netlist2c.py - turn the netlist traced from the Apple IIe schematic (tools/apple2e-netlist-src/apple2e.net, made by
apple2_sch2net.py from the Bit Preserve KiCad capture of the 050-0051-D drawing) into the board table src/apple2e_board_data.c
(bd_apple2e), same format as the other boards'.
The IIe motherboard (820-0064-B, unenhanced) names its chips by their place on the board: U, a letter for the column (F at the left
of the board as it is photographed with the slots on the right, A at the right) and a number for the row (1 at the top, 13 at the
bottom). The ICs are put on that grid with their long side across the columns, as on the board; the other parts go in rows below.
Usage: tools/apple2e_netlist2c.py [outdir]  (default: src)
"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import apple2plus_netlist2c as base      # reader, pad naming and pad rows of the Apple II+ generator

def is_ic(typ):
    return (typ.startswith('74') or typ in ('6664', '2764', '2732', '2716', '6502A', 'NE558', 'LM741', 'MMU', 'IOU', 'PAL_HAL', '3600PRO'))

def footprint(ref, typ, n):
    if typ in ('R_Small', 'R'): return 'R_Axial'
    if typ.startswith('R_Network'): return 'R_Array_SIP%d' % n
    if typ in ('C_Small', 'C_Polarized_Small'): return 'C_Disc'
    if typ in ('D_Small', 'LED_Small'): return 'D_DO-35'
    if typ == 'L_Small': return 'L_Axial'
    if typ in ('Crystal_Small', 'Oscillator'): return 'XTAL'
    if typ.startswith('Q_') or typ.startswith('2N'): return 'TO-92'
    if typ.startswith('SolderJumper'): return 'SolderJumper'
    if typ in ('VideoAmp', 'SoundAmp', 'NetTie_2'): return 'SolderJumper'
    if is_ic(typ): return 'DIP-%d' % n
    return 'CONN'

def pads_dip_across(names, x0, y0):
    """a DIP with its long side along x, notch to the left: pin 1 at the bottom left, as the chips lie on the board"""
    n = len(names)
    half = n // 2
    wr = base.dip_geom(n)
    pads = []
    for i, nm in enumerate(names, 1):
        if i <= half: x, y = x0 + (i - 1) * 2.54, y0 + wr
        else:         x, y = x0 + (n - i) * 2.54, y0
        pads.append((nm, x, y, 1.6, 1.6))
    return pads, (half * 2.54 + 2, wr + 2)

def sortkey(ref): return base.sortkey(ref)

def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'src')
    chips, nets = base.read(os.path.join(here, 'apple2e-netlist-src', 'apple2e.net'))
    padnet, pinsof = {}, {}
    for name, members in nets.items():
        if len(members) < 2 and name.startswith('N$'): continue      # a stub, not a net
        for m in members:
            ref, pin = m.rsplit('.', 1)
            padnet[(ref, pin)] = name
            pinsof.setdefault(ref, set()).add(pin)
    used = sorted({n for n in padnet.values()})
    netidx = {n: i for i, n in enumerate(used)}
    # the grid: the column of a letter is as wide as its longest chip, the row as high as its widest
    grid = {}
    loose = []
    for ref, (typ, val, n) in chips.items():
        fp = footprint(ref, typ, n)
        m = re.fullmatch(r'U([A-F])(\d{1,2})', ref)
        if m and fp.startswith('DIP'): grid[ref] = (ord('F') - ord(m.group(1)), int(m.group(2)))
        else: loose.append(ref)
    colw, rowh = {}, {}
    for ref, (c, r) in grid.items():
        n = chips[ref][2]
        colw[c] = max(colw.get(c, 0), (n // 2) * 2.54 + 6)
        rowh[r] = max(rowh.get(r, 0), base.dip_geom(n) + 6)
    colx, x = {}, 10.0
    for c in sorted(colw): colx[c] = x; x += colw[c]
    rowy, y = {}, 10.0
    for r in sorted(rowh): rowy[r] = y; y += rowh[r]
    W = max(x + 4, 330.0)
    H = y + 4
    placed = {}
    for ref, (c, r) in grid.items():
        typ, val, n = chips[ref]
        names = base.pad_names(typ, n, pinsof.get(ref, set()))
        placed[ref] = pads_dip_across(names, colx[c], rowy[r])[0]
    xx, yy, rh = 10.0, H + 8, 0.0
    for ref in sorted(loose, key=lambda r: (footprint(r, chips[r][0], chips[r][2]) != 'CONN',
                                           footprint(r, chips[r][0], chips[r][2]), sortkey(r))):
        typ, val, n = chips[ref]
        fp = footprint(ref, typ, n)
        names = base.pad_names(typ, n, pinsof.get(ref, set()))
        pads, (w, h) = base.pads_for(fp, names, xx, yy)
        if xx + w > W:
            xx, yy, rh = 10.0, yy + rh + 8, 0.0
            pads, (w, h) = base.pads_for(fp, names, xx, yy)
        placed[ref] = pads
        xx += w + 6
        rh = max(rh, h)
    height = yy + rh + 10
    out = ['/* apple2e_board_data.c - GENERATED by tools/apple2e_netlist2c.py, do not edit.\n'
           ' * Apple IIe, unenhanced (820-0064-B motherboard). The netlist is traced from the Bit Preserve KiCad capture of the 050-0051-D\n'
           ' * drawing (CC BY 4.0, baldengineer/bit-preserve) by tools/apple2_sch2net.py; the ICs sit on the board\'s grid (UE4 = column E, row 4),\n'
           ' * the rest in rows below. */\n']
    out.append('#include "board_data.h"\n\nstatic const char *const nets[] = {')
    for n in used: out.append('    "%s",' % n.replace('\\', '\\\\').replace('"', '\\"'))
    out.append('};\n\nstatic const bd_pad_t pads[] = {')
    first, comps, k = {}, [], 0
    for ref in sorted(chips, key=sortkey):
        typ, val, n = chips[ref]
        first[ref] = k
        for (nm, px, py, w, h) in placed[ref]:
            net = padnet.get((ref, nm))
            out.append('    { "%s", %.2ff, %.2ff, %.2ff, %.2ff, %d },' % (nm, px, py, w, h, netidx[net] if net else -1))
            k += 1
        comps.append((ref, typ, val, len(placed[ref])))
    out.append('};\n\nstatic const bd_comp_t comps[] = {')
    for ref, typ, val, n in comps:
        out.append('    { "%s", "%s", "%s", %d, %d },' % (ref, (val or typ).replace('"', "'"), footprint(ref, typ, n), first[ref], n))
    out.append('};\n')
    out.append('const board_data_t bd_apple2e = {\n    { 0, 0, %.0f, %.0f },\n    nets, %d, pads, %d, comps, %d };\n' % (W, height, len(used), k, len(comps)))
    path = os.path.join(outdir, 'apple2e_board_data.c')
    open(path, 'w').write('\n'.join(out))
    print(path, len(comps), 'parts', len(used), 'nets', k, 'pads')

if __name__ == '__main__':
    main()

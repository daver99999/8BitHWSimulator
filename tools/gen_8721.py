#!/usr/bin/env python3
"""gen_8721.py - turn the Verilog of the C128's 8721 PLA (tools/8721-pla.v, from a read-out of the chip) into C.

usage: python3 tools/gen_8721.py > src/c128_pla.inc

The product terms p0..p86 and the output equations are copied as they are; the two latched outputs (dwe, casenb)
are handled by the part model (c128_chips.c)."""
import re
src = re.sub(r'//[^\n]*', '', open('tools/8721-pla.v').read())
ins = re.findall(r'input\s+(\w+)', src)
terms = re.findall(r'assign\s+(p\d+)\s*=\s*(.*?);', src, re.S)
outs = re.findall(r'assign\s+(\w+)\s*=\s*([^;]*?);', src, re.S)
outs = [(n, e) for n, e in outs if not re.fullmatch(r'p\d+', n)]


def c(e):
    e = re.sub(r'//[^\n]*', '', e)          # comments
    e = e.replace('||', ' | ').replace('&', ' & ')
    e = re.sub(r'\s+', ' ', e).strip()
    # verilog: !x is logical not on one bit, here every signal is 0/1
    return re.sub(r'!\s*(\w+)', r'(!\1)', e)


print('/* generated by tools/gen_8721.py from tools/8721-pla.v - do not edit */')
print('typedef struct { int %s; } pla8721_in_t;' % ', '.join(i for i in ins))
print('typedef struct { int %s; } pla8721_out_t;' % ', '.join(n for n, _ in outs if n not in ('dwe', 'casenb', 'casenb_latch', 'casenb_int')))
print('static void pla8721_calc(const pla8721_in_t *in, pla8721_out_t *o, int *dwe_d, int *casenb_d, int *casenb_latch_o) {')
print('    int ' + ', '.join(ins) + ';')
for i in ins:
    print('    %s = in->%s;' % (i, i))
print('    (void)dmaack;                   /* an input of the chip that no output depends on */')
for n, e in terms:
    print('    int %s = %s;' % (n, c(e)))
for n, e in outs:
    if n == 'dwe' or n == 'casenb':
        continue
    if n in ('casenb_latch', 'casenb_int'):
        print('    int %s = %s;' % (n, c(e)))
    else:
        print('    o->%s = %s;' % (n, c(e)))
print('    *dwe_d = p64;')
print('    *casenb_d = casenb_int;')
print('    *casenb_latch_o = casenb_latch;')
print('}')

#!/usr/bin/env python3
"""atari800_netlist2c.py - turn the netlist of the Atari 800 (tools/atari800-netlist-src/atari800.net, made by atari800_netlist.py)
into the board table src/atari800_board_data.c (bd_atari800), same format as the other boards', and the list of the chips and their
models src/atari800_parts.inc.
The machine is four kinds of board in one netlist: the motherboard CO14175, the CPU board (A301-A303, Z301-Z304, J101C is its edge
connector), the personality board (A401-A403, Z401-Z403, PERSC) and the 16K RAM boards (refs with a suffix _1, _2, _3, RB_n their edge
connectors). Each is laid out as a region of its own; the plug-in boards' edge connectors are drawn beside the slots they go into.
Usage: tools/atari800_netlist2c.py [outdir]  (default: src)"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import board_layout_lib as base

IC_TYPES = {'GTIA', 'ANTIC', '6502', 'POKEY', 'PIA6520', 'MASKROM', 'ADDRBUF', '74LS138', '7400', '7402', '74LS03', '74LS10', '74LS32',
            '74LS42', '74LS74', '7474', '74LS158', '74LS244', 'CD4051', 'CD4050', '4116', 'CARTROM'}
CONN_TYPES = {'EDGE56', 'EDGE44', 'CART30', 'CONN22', 'DB9', 'HDR2', 'HDR4'}

def is_ic(typ): return typ in IC_TYPES

def footprint(ref, typ, n):
    if typ == 'R': return 'R_Axial'
    if typ == 'C': return 'C_Disc'
    if typ == 'D': return 'D_DO-35'
    if typ == 'L': return 'L_Axial'
    if typ == 'XTAL': return 'XTAL'
    if typ in ('NPN',): return 'TO-92'
    if typ in CONN_TYPES: return 'CONN'
    if is_ic(typ): return 'DIP-%d' % n
    return 'CONN'

def region(ref):
    m = re.search(r'_(\d)$', ref)
    if m: return 'ram' + m.group(1)
    if re.fullmatch(r'RB_\d', ref): return 'ram' + ref[-1]
    if ref in ('J101C', 'A301', 'A302', 'A303', 'Z301', 'Z302', 'Z303', 'Z304') or re.fullmatch(r'[RC]30\d|R31\d', ref): return 'cpu'
    if ref == 'PERSC' or ref in ('A401', 'A402', 'A403', 'Z401', 'Z402', 'Z403') or re.fullmatch(r'[RCL]40\d|C410', ref): return 'pers'
    return 'mb'

# (type in the netlist) -> (part type, label, role)
TYPES = {
    'GTIA': ('PT_ATARI_GTIA', 'GTIA', 'ROLE_CHIP'), 'ANTIC': ('PT_ATARI_ANTIC', 'ANTIC', 'ROLE_CHIP'),
    '6502': ('PT_PET6502', 'CPU', 'ROLE_CHIP'), 'POKEY': ('PT_ATARI_POKEY', 'POKEY', 'ROLE_CHIP'),
    'PIA6520': ('PT_PET6520', 'PIA', 'ROLE_CHIP'), 'MASKROM': ('PT_ATARI_ROM', 'ROM', 'ROLE_ROM'),
    'ADDRBUF': ('PT_ATARI_BUF', '74LS', 'ROLE_GLUE'), '74LS138': ('PT_74LS138', '74LS138', 'ROLE_GLUE'),
    '7400': ('PT_74LS00', '7400', 'ROLE_GLUE'), '7402': ('PT_74LS02', '7402', 'ROLE_GLUE'),
    '74LS03': ('PT_74LS03', '74LS03', 'ROLE_GLUE'), '74LS10': ('PT_74LS10', '74LS10', 'ROLE_GLUE'),
    '74LS32': ('PT_74LS32', '74LS32', 'ROLE_GLUE'), '74LS42': ('PT_74LS42', '74LS42', 'ROLE_GLUE'),
    '74LS74': ('PT_74LS74R', '74LS74', 'ROLE_GLUE'), '7474': ('PT_74LS74R', '74LS74', 'ROLE_GLUE'),
    '74LS158': ('PT_74LS158', '74LS158', 'ROLE_GLUE'), '74LS244': ('PT_74LS244', '74LS244', 'ROLE_GLUE'),
    'CD4051': ('PT_CD4051', 'CD4051', 'ROLE_GLUE'), 'CD4050': ('PT_CD4050', 'CD4050', 'ROLE_GLUE'),
    '4116': ('PT_4116', 'RAM', 'ROLE_RAM'), 'CARTROM': ('PT_ATARI_CART', 'ROM', 'ROLE_ROM'),
}
WHAT = {
    'A301': 'GTIA (CTIA successor, C014805): colour and luminance, players, missiles, collisions, console switches and triggers',
    'A302': 'ANTIC (C012296): display list, playfield and player/missile DMA, refresh, vertical blank and display list NMIs',
    'A303': '6502 CPU, 1.79 MHz: its phase-0 clock is gated by Z301 and stopped while ANTIC halts it',
    'A101': 'POKEY (C012294): sound, keyboard scan, pots, timers, serial bus',
    'A102': '6520 PIA: the joystick directions of the four controller ports, serial bus handshake lines',
    'A401': 'OS ROM F, 4K: $F000-$FFFF (rev B, 10K OS in three chips)', 'A402': 'OS ROM D, 2K: $D800-$DFFF',
    'A403': 'OS ROM E, 4K: $E000-$EFFF', 'CARTL': 'plug-in cartridge in the left slot (J109): the 8K BASIC ROM at $A000-$BFFF, nothing fitted until one is loaded',
    'Z101': '74LS42: address decoder, A13-A15 to the eight 8K blocks S0-S7', 'Z102': '74LS32: gates S4 / S5 off when a cartridge pulls RD4 / RD5',
    'Z103': 'CD4051: keyboard scan, the column POKEY pulls low', 'Z104': 'CD4051: keyboard return, the row that POKEY reads',
    'Z301': '7402: gates the 6502 phase 0 and the bus read/write line', 'Z302': '74LS74: PHI1 / PHI2 and the halt synchroniser',
    'Z303': 'address buffer A0-A7 from the CPU to the bus', 'Z304': 'address buffer A8-A15 from the CPU to the bus',
    'Z401': '74LS138: decodes $D0xx-$D7xx page selects from A8-A10', 'Z402': '7400: RASTIME and WRITIME timing gates',
    'Z403': '74LS03 (open collector): EXSEL and the bus grant', 'A103': 'CD4050 buffer: power-on reset and the luminance mixer',
    'A104': 'CD4050 buffer: chroma', 'X101': '3.579545 MHz crystal (modelled as a clock source on OSC)',
}

def partdefs(chips):
    out = ['/* atari800_parts.inc - GENERATED by tools/atari800_netlist2c.py, do not edit: the chips of the Atari 800 and their models. */']
    for ref in sorted(chips, key=base.sortkey):
        typ, val, n = chips[ref]
        if typ == 'XTAL':
            out.append('    { "%s", &PT_XTAL358, "3.579545", ROLE_CLOCK, NULL, "%s" },' % (ref, WHAT[ref])); continue
        if typ not in TYPES: continue
        pt, lab, role = TYPES[typ]
        what = WHAT.get(ref) or WHAT.get(re.sub(r'_\d$', '', ref)) or val
        m = re.fullmatch(r'Z(50[5-9]|51[0-2])_(\d)', ref)
        if m:
            bit = {'Z505': 6, 'Z506': 7, 'Z507': 5, 'Z508': 3, 'Z509': 4, 'Z510': 2, 'Z511': 1, 'Z512': 0}['Z' + m.group(1)]
            what = '4116 DRAM, 16K x 1: bit %d of the 16K RAM board in slot %d' % (bit, int(m.group(2)))
        elif re.fullmatch(r'Z50[1-4]_\d', ref):
            what = {'Z501': '74LS10: RAM read enable, RAS', 'Z502': '74LS244: RAM data out onto the bus', 'Z503': '74LS158: RAM address multiplexer',
                    'Z504': '74LS158: RAM address multiplexer and CAS'}[ref[:4]] + ' (16K RAM board %s)' % ref[-1]
        out.append('    { "%s", &%s, "%s", %s, NULL, "%s" },' % (ref, pt, lab, role, what.replace('"', "'")))
    return '\n'.join(out) + '\n'

def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'src')
    chips, nets = base.read(os.path.join(here, 'atari800-netlist-src', 'atari800.net'))
    padnet, pinsof = {}, {}
    for name, members in nets.items():
        for m in members:
            ref, pin = m.rsplit('.', 1)
            padnet[(ref, pin)] = name
            pinsof.setdefault(ref, set()).add(pin)
    used = sorted({n for n in padnet.values()})
    netidx = {n: i for i, n in enumerate(used)}
    regs = {}
    for ref in chips: regs.setdefault(region(ref), []).append(ref)
    placed = {}

    def flow(refs, x0, y0, width):
        """ICs in rows of DIPs (long side down), connectors beside, the other parts in a strip under; returns the height used"""
        x, y, rowh = x0, y0, 0.0
        ics = sorted([r for r in refs if footprint(r, *chips[r][0:1], chips[r][2]).startswith('DIP')], key=base.sortkey)
        for ref in ics:
            typ, val, n = chips[ref]
            names = base.pad_names(typ, n, pinsof.get(ref, set()))
            pads, (w, h) = base.pads_for('DIP-%d' % n, names, x, y)
            if x + w > x0 + width and x > x0:
                x, y, rowh = x0, y + rowh + 3, 0.0
                pads, (w, h) = base.pads_for('DIP-%d' % n, names, x, y)
            placed[ref] = pads; x += w + 3; rowh = max(rowh, h)
        y += rowh + 4
        x, rowh = x0, 0.0
        rest = sorted([r for r in refs if r not in placed], key=lambda r: (footprint(r, chips[r][0], chips[r][2]) != 'CONN',
                                                                         footprint(r, chips[r][0], chips[r][2]), base.sortkey(r)))
        for ref in rest:
            typ, val, n = chips[ref]
            fp = footprint(ref, typ, n)
            names = base.pad_names(typ, n, pinsof.get(ref, set()))
            pads, (w, h) = base.pads_for(fp, names, x, y)
            if x + w > x0 + width and x > x0:
                x, y, rowh = x0, y + rowh + 3, 0.0
                pads, (w, h) = base.pads_for(fp, names, x, y)
            placed[ref] = pads; x += w + 3; rowh = max(rowh, h)
        return y + rowh + 6

    W = 330.0
    y = 10.0
    for name, width in (('mb', W - 20), ('cpu', 150.0), ('pers', 150.0), ('ram1', 150.0), ('ram2', 150.0), ('ram3', 150.0)):
        if name not in regs: continue
        x0 = 10.0 + (170.0 if name in ('pers', 'ram2') else 0.0)
        if name == 'pers': y -= placed_h
        if name == 'ram2': y -= placed_h
        placed_h = flow(regs[name], x0, y, width) - y
        y += placed_h
    H = y + 6
    out = ['/* atari800_board_data.c - GENERATED by tools/atari800_netlist2c.py, do not edit.\n'
           ' * Atari 800 (motherboard CO14175 Rev A with its CPU board, personality board and 16K RAM boards). The netlist is typed in from the\n'
           ' * Atari 400/800 Field Service Manual, Section 2; the boards are laid out as regions: the motherboard on top, the plug-in boards below. */\n']
    out.append('#include "board_data.h"\n\nstatic const char *const nets[] = {')
    for n in used: out.append('    "%s",' % n.replace('\\', '\\\\').replace('"', '\\"'))
    out.append('};\n\nstatic const bd_pad_t pads[] = {')
    first, comps, k = {}, [], 0
    for ref in sorted(chips, key=base.sortkey):
        typ, val, n = chips[ref]
        first[ref] = k
        for (nm, px, py, w, h) in placed[ref]:
            net = padnet.get((ref, nm))
            out.append('    { "%s", %.2ff, %.2ff, %.2ff, %.2ff, %d },' % (nm, px, py, w, h, netidx[net] if net else -1))
            k += 1
        comps.append((ref, typ, val, len(placed[ref])))
    out.append('};\n\nstatic const bd_comp_t comps[] = {')
    for ref, typ, val, n in comps:
        out.append('    { "%s", "%s", "%s", %d, %d },' % (ref, (val or typ).replace('"', "'"), footprint(ref, typ, n), first[ref], n))
    out.append('};\n')
    out.append('const board_data_t bd_atari800 = {\n    { 0, 0, %.0f, %.0f },\n    nets, %d, pads, %d, comps, %d };\n' % (W, H, len(used), k, len(comps)))
    open(os.path.join(outdir, 'atari800_board_data.c'), 'w').write('\n'.join(out))
    open(os.path.join(outdir, 'atari800_parts.inc'), 'w').write(partdefs(chips))
    print('atari800_board_data.c', len(comps), 'parts', len(used), 'nets', k, 'pads', '%.0f x %.0f' % (W, H))

if __name__ == '__main__':
    main()

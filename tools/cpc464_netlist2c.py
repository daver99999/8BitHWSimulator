#!/usr/bin/env python3
"""cpc464_netlist2c.py - turn the CPC 464 netlist (tools/cpc464-netlist-src/cpc464.net, made by cpc464_netlist.py) into the board table
src/cpc464_board_data.c (bd_cpc464) and src/cpc464_parts.inc (the chips that already have a simulator model).
Chips with no model yet (8255, AY-3-8912, the gate array, 74LS132, the 32K ROM) are in the board table only: they are probed for
continuity but not simulated.   Usage: tools/cpc464_netlist2c.py [outdir]  (default: src)"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import board_layout_lib as base

IC_TYPES = {'Z80', 'ROM32K', 'PPI8255', 'AY8912', 'LS145', 'LS132', 'LS32', 'LS273', 'CRTC6845', 'LS153', 'LS244', 'LS373', 'GATEARRAY',
            'ZN7400', 'DRAM4164'}
CONN_TYPES = {'CONN'}
MODEL = {'Z80': ('PT_Z80A', 'CPU', 'ROLE_CHIP'), 'LS145': ('PT_74LS145', '74LS145', 'ROLE_GLUE'), 'LS32': ('PT_74LS32', '74LS32', 'ROLE_GLUE'),
         'LS273': ('PT_74LS273', '74LS273', 'ROLE_GLUE'), 'CRTC6845': ('PT_PET6545', 'CRTC', 'ROLE_CHIP'), 'LS153': ('PT_74LS153', '74LS153', 'ROLE_GLUE'),
         'LS244': ('PT_74LS244', '74LS244', 'ROLE_GLUE'), 'LS373': ('PT_74LS373', '74LS373', 'ROLE_GLUE'), 'ZN7400': ('PT_74LS00', '7400', 'ROLE_GLUE'),
         'DRAM4164': ('PT_4164', 'RAM', 'ROLE_RAM')}

def footprint(ref, typ, n):
    if typ == 'R': return 'R_Axial'
    if typ in ('C', 'CE'): return 'C_Disc'
    if typ == 'D': return 'D_DO-35'
    if typ == 'XTAL': return 'XTAL'
    if typ in ('NPN', 'PNP'): return 'TO-92'
    if typ in IC_TYPES: return 'DIP-%d' % n
    return 'CONN'

def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'src')
    chips, nets = base.read(os.path.join(here, 'cpc464-netlist-src', 'cpc464.net'))
    padnet, pinsof = {}, {}
    for name, members in nets.items():
        for m in members:
            ref, pin = m.rsplit('.', 1)
            padnet[(ref, pin)] = name
            pinsof.setdefault(ref, set()).add(pin)
    used = sorted(set(padnet.values()))
    netidx = {n: i for i, n in enumerate(used)}
    placed = {}
    W = 300.0
    x0, x, y, rowh = 10.0, 10.0, 10.0, 0.0
    def put(ref):
        nonlocal x, y, rowh
        typ, val, n = chips[ref]
        fp = footprint(ref, typ, n)
        names = base.pad_names(typ, n, pinsof.get(ref, set()))
        pads, (w, h) = base.pads_for(fp, names, x, y)
        if x + w > x0 + W and x > x0:
            x, y, rowh = x0, y + rowh + 3, 0.0
            pads, (w, h) = base.pads_for(fp, names, x, y)
        placed[ref] = pads; x += w + 3; rowh = max(rowh, h)
    for ref in sorted((r for r in chips if footprint(r, chips[r][0], chips[r][2]).startswith('DIP')), key=base.sortkey): put(ref)
    x, y, rowh = x0, y + rowh + 4, 0.0
    for ref in sorted((r for r in chips if r not in placed), key=lambda r: (footprint(r, chips[r][0], chips[r][2]) != 'CONN',
                                                                         footprint(r, chips[r][0], chips[r][2]), base.sortkey(r))): put(ref)
    H = y + rowh + 6
    out = ['/* cpc464_board_data.c - GENERATED by tools/cpc464_netlist2c.py, do not edit.\n'
           ' * Amstrad CPC 464 main board (Z70100). The netlist is typed in from the CPC 464 circuit diagram and checked by continuity\n'
           ' * (docs/CPC464_BEEP_CHECKS.md). */\n', '#include "board_data.h"\n\nstatic const char *const nets[] = {']
    for n in used: out.append('    "%s",' % n.replace('\\', '\\\\').replace('"', '\\"'))
    out.append('};\n\nstatic const bd_pad_t pads[] = {')
    first, comps, k = {}, [], 0
    for ref in sorted(chips, key=base.sortkey):
        typ, val, n = chips[ref]
        first[ref] = k
        for (nm, px, py, w, h) in placed[ref]:
            net = padnet.get((ref, nm))
            out.append('    { "%s", %.2ff, %.2ff, %.2ff, %.2ff, %d },' % (nm, px, py, w, h, netidx[net] if net else -1))
            k += 1
        comps.append((ref, typ, val, len(placed[ref])))
    out.append('};\n\nstatic const bd_comp_t comps[] = {')
    for ref, typ, val, n in comps:
        out.append('    { "%s", "%s", "%s", %d, %d },' % (ref, (val or typ).replace('"', "'"), footprint(ref, typ, n), first[ref], n))
    out.append('};\n')
    out.append('const board_data_t bd_cpc464 = {\n    { 0, 0, %.0f, %.0f },\n    nets, %d, pads, %d, comps, %d };\n' % (W, H, len(used), k, len(comps)))
    open(os.path.join(outdir, 'cpc464_board_data.c'), 'w').write('\n'.join(out))
    inc = ['/* cpc464_parts.inc - GENERATED by tools/cpc464_netlist2c.py, do not edit: the CPC 464 chips that have a model. */']
    nomodel = []
    for ref in sorted(chips, key=base.sortkey):
        typ, val, n = chips[ref]
        if typ in MODEL:
            pt, lab, role = MODEL[typ]
            inc.append('    { "%s", &%s, "%s", %s, NULL, "%s" },' % (ref, pt, lab, role, val.replace('"', "'")))
        elif typ in IC_TYPES: nomodel.append(ref)
    open(os.path.join(outdir, 'cpc464_parts.inc'), 'w').write('\n'.join(inc) + '\n')
    print('cpc464_board_data.c', len(comps), 'parts', len(used), 'nets', k, 'pads', '%.0f x %.0f' % (W, H))
    print('no model yet:', ' '.join(nomodel))

if __name__ == '__main__':
    main()
